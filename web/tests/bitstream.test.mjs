// UG470 Table 5-19 words: dummy, bus-width pattern, sync word, NOOP.
const DUMMY_WORD = 0xffffffff;
const BUS_WIDTH_PATTERN = [0x000000bb, 0x11220044];
const SYNC_WORD = 0xaa995566;
const NOOP = 0x20000000;
// UG470 Table 5-23 register addresses.
const REGISTER_FDRI = 0b00010;
const REGISTER_CMD = 0b00100;
const REGISTER_IDCODE = 0b01100;
// UG470 Table 1-1: XC7A35T.
const IDCODE_XC7A35T = 0x0362d093;
// First note of every bitstream payload.
const FPGA_NOTE = 'FPGA configuration data, not CPU code; excluded from ISA analysis';

// CRC-16/IBM-3740: polynomial 0x1021, MSB first, initial value 0xFFFF.
function crc16Ibm3740(bytes) {
  let crc = 0xffff;
  for (const b of bytes) {
    crc ^= b << 8;
    for (let i = 0; i < 8; i++) {
      crc = crc & 0x8000 ? ((crc << 1) ^ 0x1021) & 0xffff : (crc << 1) & 0xffff;
    }
  }
  return crc;
}

// CRC-16/MODBUS: reflected polynomial 0xA001, initial value 0xFFFF.
function crc16Modbus(bytes) {
  let crc = 0xffff;
  for (const b of bytes) {
    crc ^= b;
    for (let i = 0; i < 8; i++) {
      crc = crc & 1 ? (crc >>> 1) ^ 0xa001 : crc >>> 1;
    }
  }
  return crc;
}

// UG470 Type 1 write header: type 001, opcode 10, register, word count.
const type1Write = (register, words) => ((0b001 << 29) | (0b10 << 27) | (register << 13) | words) >>> 0;

// UG470 Type 2 write header: type 010, opcode 10, word count.
const type2Write = words => ((0b010 << 29) | (0b10 << 27) | words) >>> 0;

// 7 series configuration words: eight dummy words, the bus-width pattern,
// two dummy words, the sync word, a NOOP, the IDCODE write, an FDRI write
// of four synthetic words, DESYNC and two NOOPs.
function series7Words() {
  return [
    ...Array(8).fill(DUMMY_WORD),
    ...BUS_WIDTH_PATTERN,
    DUMMY_WORD,
    DUMMY_WORD,
    SYNC_WORD,
    NOOP,
    type1Write(REGISTER_IDCODE, 1),
    IDCODE_XC7A35T,
    type1Write(REGISTER_FDRI, 0),
    type2Write(4),
    0x01020304,
    0x05060708,
    0x090a0b0c,
    0x0d0e0f10,
    type1Write(REGISTER_CMD, 1),
    0x0000000d,
    NOOP,
    NOOP,
  ];
}

function bigEndianWords(words) {
  const bytes = Buffer.alloc(words.length * 4);
  words.forEach((word, i) => bytes.writeUInt32BE(word, i * 4));
  return bytes;
}

// One .bit header field: key, 16-bit big-endian length, NUL-terminated text.
function bitField(key, value) {
  const field = Buffer.alloc(3 + value.length + 1);
  field.write(key, 0);
  field.writeUInt16BE(value.length + 1, 1);
  field.write(value, 3);
  return field;
}

// .bit file: 13-byte prefix, keys a-d, key e with the 32-bit data length.
function bitFile(configuration) {
  const prefix = Buffer.from([0x00, 0x09, 0x0f, 0xf0, 0x0f, 0xf0, 0x0f, 0xf0, 0x0f, 0xf0, 0x00, 0x00, 0x01]);
  const length = Buffer.alloc(5);
  length.write('e', 0);
  length.writeUInt32BE(configuration.length, 1);
  return Buffer.concat([
    prefix,
    bitField('a', 'top;UserID=0XFFFFFFFF;Version=2023.2'),
    bitField('b', '7a35tcpg236'),
    bitField('c', '2026/10/12'),
    bitField('d', '12:00:00'),
    length,
    configuration,
  ]);
}

// iCE40 bitstream: comment block (FF 00, strings, 00 FF), preamble,
// oscillator range, CRC reset, one 16 x 4 CRAM bank with its 00 00
// terminator, the CRC check, wakeup and one padding byte.
function ice40() {
  const comment = Buffer.concat([
    Buffer.from([0xff, 0x00]),
    Buffer.from('Generated by test\0'),
    Buffer.from([0x00, 0xff]),
  ]);
  const commands = [0x62, 0x00, 0x0f, 0x72, 0x00, 0x04, 0x82, 0x00, 0x00, 0x11, 0x00, 0x01, 0x01];
  const covered = Buffer.from([...commands, 1, 2, 3, 4, 5, 6, 7, 8, 0x00, 0x00, 0x22]);
  const crc = crc16Ibm3740(covered);
  return Buffer.concat([
    comment,
    Buffer.from([0x7e, 0xaa, 0x99, 0x7e, 0x51, 0x00, 0x01, 0x05]),
    covered,
    Buffer.from([crc >> 8, crc & 0xff, 0x01, 0x06, 0x00]),
  ]);
}

// ECP5 bitstream: FF 00, a comment string, FF, the preamble FF FF BD B3,
// dummy bytes, LSC_RESET_CRC, VERIFY_ID with the LFE5U-25F IDCODE, then
// synthetic frame bytes.
function ecp5() {
  return Buffer.concat([
    Buffer.from([0xff, 0x00]),
    Buffer.from('Part: LFE5U-25F-6CABGA256\0'),
    Buffer.from([0xff, 0xff, 0xff, 0xbd, 0xb3, 0xff, 0xff, 0xff, 0xff]),
    Buffer.from([0x3b, 0, 0, 0, 0xe2, 0, 0, 0, 0x41, 0x11, 0x10, 0x43]),
    Buffer.from([0x46, 0, 0, 0, 1, 2, 3, 4]),
  ]);
}

// Cyclone V .rbf option frame: FF x 0x80, 'jjjj', option RAM and two zero
// bytes, little-endian CRC-16/MODBUS over them, then FF fill.
function cycloneV() {
  const optionRam = Buffer.alloc(0xa2);
  optionRam[0] = 0x80;
  const crc = Buffer.alloc(2);
  crc.writeUInt16LE(crc16Modbus(optionRam));
  return Buffer.concat([Buffer.alloc(0x80, 0xff), Buffer.from('jjjj'), optionRam, crc, Buffer.alloc(0x40, 0xff)]);
}

// POF packet: 16-bit tag, 32-bit length (little-endian), payload.
function pofPacket(tag, payload) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(tag, 0);
  header.writeUInt32LE(payload.length, 2);
  return Buffer.concat([header, payload]);
}

// POF: magic, unknown word, packet count, part name and configuration data.
function pof() {
  const packets = [
    pofPacket(0x02, Buffer.from('10M08SAE144C8G\0')),
    pofPacket(0x11, Buffer.concat([Buffer.alloc(12), Buffer.from([1, 2, 3, 4, 5, 6, 7, 8])])),
  ];
  const header = Buffer.alloc(12);
  header.write('POF\0', 0);
  header.writeUInt32LE(packets.length, 8);
  return Buffer.concat([header, ...packets]);
}

const FIXTURES = [
  ['design.bit', bitFile(bigEndianWords(series7Words())), 'xilinxbit'],
  ['design.bin', bigEndianWords(series7Words()), 'xilinxbit'],
  ['ice40.bin', ice40(), 'latticebitstream'],
  ['ecp5.bit', ecp5(), 'latticebitstream'],
  ['cyclonev.rbf', cycloneV(), 'intelfpga'],
  ['design.pof', pof(), 'intelfpga'],
];

for (const module of ['/pkg/zrax.js', '/dist/zrax.js']) {
  test(`bitstreams are recognized and kept out of ISA analysis through ${module}`, async t => {
    const page = await openPage(t);
    await page.goto(baseUrl + '/web/index.html');
    const fixtures = FIXTURES.map(([name, bytes, format]) => ({ name, format, bytes: [...bytes] }));
    const payloads = await page.evaluate(async ({ module, fixtures }) => {
      const wasm = await import(module);
      await wasm.default();
      return Object.fromEntries(fixtures.map(f => [f.name, JSON.parse(wasm.classify(new Uint8Array(f.bytes)))]));
    }, { module, fixtures });
    for (const { name, format } of fixtures) {
      const p = payloads[name];
      assert.ok(!p.error, `${name}: ${p.error}`);
      assert.equal(p.format.format, format, name);
      assert.ok(Object.hasOwn(FORMAT_NAMES, format), `${format} has a display name`);
      assert.deepEqual(p.primary.isa, { unknown: 0 }, name);
      assert.equal(p.primary.confidence, 0, name);
      assert.deepEqual(p.candidates, [], name);
      assert.equal(p.slices[0].label, 'Configuration data', name);
      assert.ok(p.notes.some(n => n.message === FPGA_NOTE), name);
    }
    const bit = payloads['design.bit'];
    assert.ok(bit.notes.some(n => n.message === 'Part: 7a35tcpg236'));
    assert.ok(bit.notes.some(n => n.message.startsWith('Device IDCODE 0x0362D093')));
    assert.equal(payloads['design.bin'].format.variant_name, 'Xilinx raw bitstream');
    assert.ok(payloads['ice40.bin'].notes.some(n => n.message === 'CRC-16 verified at 1 check command'));
    assert.ok(payloads['ecp5.bit'].notes.some(n => n.message.includes('LFE5U-25F (prjtrellis devices.json)')));
  });
}

for (const path of ['/web/index.html', '/dist/index.html']) {
  test(`the workbench names Xilinx bitstreams and keeps the stored offset in ${path}`, async t => {
    const page = await openPage(t);
    await load(page, path);
    const configuration = bigEndianWords(series7Words());
    const buffer = bitFile(configuration);
    const file = { name: 'design.bit', buffer, mimeType: 'application/octet-stream' };
    await page.locator('#fileinput').setInputFiles([file]);
    await finished(page, 1);
    await selectEntry(page, 0);
    const content = await page.locator('#classification-content').textContent();
    assert.ok(content.includes('Xilinx bitstream'), content);
    await page.getByRole('tab', { name: 'json', exact: true }).click();
    const p = JSON.parse(await page.locator('#jsonRaw').textContent());
    assert.equal(p.format.format, 'xilinxbit');
    assert.equal(p.slices[0].offset, buffer.length - configuration.length);
    assert.ok(p.metadata.some(m => m.key?.custom === 'bitstream_part' && m.value === '7a35tcpg236'));
  });
}
