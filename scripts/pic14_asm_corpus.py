#!/usr/bin/env python3
"""Hand-written mid-range PIC (14-bit core) code from open-source repositories.

The `pic14` class was trained on SDCC output only, which does not look like
hand-written PIC assembly: a PIC12C671 program in the fw1 set scored 6.89
bits/byte under PA-RISC and worse under `pic14`. This script adds hand-written
code for the class:

1. each repository in REPOS (TSV: `owner/name`, SPDX license, branch) is
   pinned to the branch head commit with `git ls-remote`, and its tarball is
   downloaded from codeload.github.com and extracted (paths checked) into
   WORK/src/<owner>__<name>/;
2. every hand-written `.asm` file that names a mid-range processor
   (`list p=`, `processor`, or an `#include <p16f...inc>`) is assembled with
   gpasm in absolute mode; the relocatable modules of one directory are
   assembled with `gpasm -c` and linked together with gplink's default
   linker script; compiler output (SDCC, XC8, HI-TECH, CC5X, mikroC) and
   sources that fail to assemble or link are skipped;
3. program-memory words are taken from the Intel HEX output (word addresses
   below 0x2000, or below 0x8000 on enhanced mid-range parts); configuration,
   ID and EEPROM records are dropped, and the words are written little-endian
   in address order, as the CPU fetches them;
4. the programs of one repository are concatenated into one sample,
   OUT/<owner>__<name>.bin, so that versions of a program stay in one
   train/test group (build_corpus.py groups `--raw` files by file name);
   identical programs are kept once.

Baseline (12-bit: PIC10F2xx, PIC12F5xx, PIC16F5x, ...) and PIC18 sources are
skipped: they are other instruction sets. Sources whose path names the fw1
test file (`hop_leds`) are skipped, so that file stays held out.

One provenance row per repository is appended to PROVENANCE (markdown table
row in the format of corpus_extra/raw-ext/PROVENANCE.md). The corpus class is
the name of OUT: `corpus_extra/raw-ext/pic14asm` feeds the `pic14asm` class,
which holds hand-written code apart from the SDCC-trained `pic14` class.

Usage:
    pic14_asm_corpus.py REPOS WORK OUT PROVENANCE
"""
import argparse
import hashlib
import importlib.util
import os
import re
import subprocess

# Loaded by path: `python3 -I` keeps the script directory off sys.path.
_spec = importlib.util.spec_from_file_location(
    "github_repos", os.path.join(os.path.dirname(os.path.abspath(__file__)), "github_repos.py"))
github_repos = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(github_repos)
read_text = github_repos.read_text

# Word address limits of program memory (PIC16F84A/877A data sheets: the
# configuration word is at 0x2007; enhanced mid-range parts such as the
# PIC16F1455 keep configuration words at 0x8007).
CLASSIC_PROGRAM_WORDS = 0x2000
ENHANCED_PROGRAM_WORDS = 0x8000
ASSEMBLE_TIMEOUT_SECONDS = 30
HELD_OUT_NAMES = ("hop_leds",)

LIST_PROCESSOR = re.compile(r"(?im)^[ \t]*list\b[^;\n]*?\bp\s*=\s*(?:pic)?([0-9a-z]+)")
PROCESSOR_DIRECTIVE = re.compile(r"(?im)^[ \t]*processor[ \t]+(?:pic)?([0-9a-z]+)")
INCLUDE_PROCESSOR = re.compile(r"(?im)^[ \t]*#?include[ \t]*[<\"]p(1[026][0-9a-z]+)\.inc[>\"]")
RELOCATABLE = re.compile(r"(?im)^[ \t]*\w*[ \t]+(?:code|udata|udata_shr|idata)\b")
# Compiler output is not hand-written code (SDCC, XC8, HI-TECH, CC5X and
# mikroC listings are committed as .asm in some repositories).
COMPILER_OUTPUT = re.compile(
    r"(?im)generated by\s+(?:sdcc|mplab|xc8|hi-tech|cc5x|mikro)|^[ \t]*\.file\b|^[ \t]*extern\b"
)
# 12-bit baseline cores and PIC18 (another instruction set each).
BASELINE_OR_PIC18 = re.compile(r"^(10f2\d\d|12[cf]5\d\d|16[cf]5\d+[a-z]?|16f5[0-7]\d|18[a-z]*\d+)")
ENHANCED = re.compile(r"^1[026]f1\d{3,}")


def processor_of(source):
    """The processor a source file names, lower case without `pic`, or None."""
    for pattern in (LIST_PROCESSOR, PROCESSOR_DIRECTIVE, INCLUDE_PROCESSOR):
        match = pattern.search(source)
        if match:
            return match.group(1).lower()
    return None


def hex_records(text):
    """(byte address, data) of every data record of an INHX32 file."""
    upper = 0
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith(":") or len(line) < 11:
            continue
        raw = bytes.fromhex(line[1:])
        count, address, kind = raw[0], int.from_bytes(raw[1:3], "big"), raw[3]
        payload = raw[4:4 + count]
        if kind == 0:
            yield (upper << 16) + address, payload
        elif kind == 4:
            upper = int.from_bytes(payload, "big")


def program_words(hex_text, enhanced):
    """Program-memory bytes in word-address order (little-endian words)."""
    limit = 2 * (ENHANCED_PROGRAM_WORDS if enhanced else CLASSIC_PROGRAM_WORDS)
    memory = {}
    for address, payload in hex_records(hex_text):
        for i, value in enumerate(payload):
            if address + i < limit:
                memory[address + i] = value
    return bytes(memory[a] for a in sorted(memory))


def scratch_path(scratch, key, suffix):
    return os.path.join(scratch, hashlib.sha1(key.encode()).hexdigest()[:16] + suffix)


def run_tool(command, cwd, output):
    """Run gpasm or gplink; True if it succeeded and wrote output."""
    try:
        result = subprocess.run(command, cwd=cwd, capture_output=True, timeout=ASSEMBLE_TIMEOUT_SECONDS)
    except subprocess.TimeoutExpired:
        return False
    return result.returncode == 0 and os.path.exists(output)


def assemble(dirpath, name, processor, scratch):
    """gpasm's hex output for one absolute-mode source, or None."""
    hex_path = scratch_path(scratch, os.path.join(dirpath, name), ".hex")
    command = ["gpasm", "-q", "-w", "2", "-p", processor, "-o", hex_path, name]
    return read_text(hex_path) if run_tool(command, dirpath, hex_path) else None


def link(dirpath, names, processor, scratch):
    """gplink's hex output for the relocatable modules of one directory, or None.

    The modules of a project reference each other, so they are linked as one
    program with gplink's default linker script for the processor.
    """
    objects = []
    for name in names:
        object_path = scratch_path(scratch, os.path.join(dirpath, name), ".o")
        if not run_tool(["gpasm", "-c", "-q", "-w", "2", "-p", processor, "-o", object_path, name], dirpath, object_path):
            return None
        objects.append(object_path)
    hex_path = scratch_path(scratch, dirpath, ".hex")
    return read_text(hex_path) if run_tool(["gplink", "-q", "-o", hex_path, *objects], dirpath, hex_path) else None


def hand_written_sources(tree, dirpath, files):
    """(name, processor, relocatable) of the hand-written mid-range sources in one directory."""
    for name in sorted(files):
        if not name.lower().endswith(".asm"):
            continue
        relative = os.path.relpath(os.path.join(dirpath, name), tree)
        if any(held in relative.lower() for held in HELD_OUT_NAMES):
            continue
        source = read_text(os.path.join(dirpath, name))
        if COMPILER_OUTPUT.search(source):
            continue
        processor = processor_of(source)
        yield name, processor, bool(RELOCATABLE.search(source))


def repo_programs(tree, scratch):
    """(relative path, processor, code bytes) of every program in a source tree.

    Absolute-mode sources are programs on their own; the relocatable modules
    of a directory form one program, named after the directory.
    """
    for dirpath, _, files in os.walk(tree):
        sources = list(hand_written_sources(tree, dirpath, files))
        modules = [name for name, _, relocatable in sources if relocatable]
        module_processors = {processor for _, processor, relocatable in sources if relocatable and processor}
        for name, processor, relocatable in sources:
            if relocatable or processor is None or BASELINE_OR_PIC18.match(processor):
                continue
            hex_text = assemble(dirpath, name, processor, scratch)
            if hex_text is not None:
                code = program_words(hex_text, bool(ENHANCED.match(processor)))
                if code:
                    yield os.path.relpath(os.path.join(dirpath, name), tree), processor, code
        # Modules that name different processors are not one program.
        if modules and len(module_processors) == 1:
            processor = module_processors.pop()
            if BASELINE_OR_PIC18.match(processor):
                continue
            hex_text = link(dirpath, modules, processor, scratch)
            if hex_text is not None:
                code = program_words(hex_text, bool(ENHANCED.match(processor)))
                if code:
                    yield os.path.relpath(dirpath, tree) + "/", processor, code


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("repos", help="TSV: owner/name, SPDX license, branch")
    parser.add_argument("work", help="download and scratch directory")
    parser.add_argument("out", help="output directory (one .bin per repository); its name is the corpus class")
    parser.add_argument("provenance", help="markdown file to append provenance rows to")
    args = parser.parse_args()
    # gpasm runs in the source directory, so the output path must be absolute.
    scratch = os.path.abspath(os.path.join(args.work, "hex"))
    os.makedirs(scratch, exist_ok=True)

    def describe(count, processors):
        return (f"gpasm/gplink 1.5.2 build of {count} program(s) ({', '.join(sorted(processors))}); "
                "program-memory words from the hex, configuration, ID and EEPROM dropped")

    github_repos.harvest(args.repos, args.work, args.out, args.provenance,
                         lambda tree: repo_programs(tree, scratch), describe)


if __name__ == "__main__":
    main()
