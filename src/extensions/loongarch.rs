//! LoongArch extension evidence: LSX (128-bit) and LASX (256-bit) vectors.
//!
//! Instructions are 32-bit little-endian words. Each word is looked up by its
//! top 17 bits in a table of ranges generated from LLVM's LoongArch decoder
//! (LLVM 23, `+lsx,+lasx,+lvz,+lbt,+f,+d,...`): every 17-bit prefix was
//! sampled 16 times and labelled *invalid* (nothing decodes), *LSX* (`v*`
//! mnemonics), *LASX* (`xv*`, `vext2xv*`) or *other valid*. About 64 percent
//! of the 32-bit space is unallocated, which makes block gating effective.
//! LBT and LVZ share opcode prefixes with branch instructions at this
//! granularity, so they are not reported.

use super::{bit_of, ExtDef, Tally};
use crate::types::{Endianness, ExtensionCategory::*, Isa};

