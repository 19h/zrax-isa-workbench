    #[test]
    fn loongarch_encodings() {
        for &(w, want) in WORDS {
            assert_eq!(classify(w), want, "{w:#010X}");
        }
    }

    #[test]
    fn lasx_loop() {
        // xvld; xvld; xvfmadd.s; xvst; addi.d $a0, $a0, 32; bne $a1, $a0, -24
        let f = [0x2C808080u32, 0x2C808081, 0x0A118820, 0x2CC08080, 0x02C08084, 0x5FFFE8A4];
        let code = le_words(&f.repeat(500));
        assert_eq!(detect(&code, Isa::LoongArch64, Endianness::Little), vec!["LASX"]);
        let f = [0x02C08084u32, 0x001098A4, 0x28C020A4, 0x4C000020];
        assert!(detect(&le_words(&f.repeat(500)), Isa::LoongArch64, Endianness::Little).is_empty());
    }
