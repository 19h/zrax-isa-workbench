pub(super) fn scan(code: &[u8], _isa: Isa, _e: Endianness, t: &mut Tally) {
    for c in code.chunks_exact(4) {
        match classify(u32::from_le_bytes([c[0], c[1], c[2], c[3]])) {
            Some(m) => t.insn(m),
            None => t.invalid(),
        }
    }
}

/// Evidence bits of one instruction word; `None` if unallocated.
pub(crate) fn classify(w: u32) -> Option<u64> {
    if w == 0 {
        return None; // not an instruction; zero fill
    }
    let prefix = w >> 15;
    let i = RUNS.partition_point(|&r| r >> 2 <= prefix) - 1;
    match RUNS[i] & 3 {
        0 => None,
        1 => Some(0),
        2 => Some(LSX),
        _ => Some(LASX),
    }
}

