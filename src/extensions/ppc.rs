//! PowerPC extension evidence: AltiVec/VMX, VSX, MMA, HTM, in-core crypto, SPE.
//!
//! Instructions are 32-bit words in the data byte order (ppc64le: little
//! endian). The class of a word is looked up by (primary opcode, low 11 bits)
//! for the primary opcodes that carry vector instructions (4, 6, 31, 57, 59,
//! 60, 61, 63), and by primary opcode alone otherwise. The tables were
//! generated from LLVM's PowerPC decoder (LLVM 23, `-mcpu=pwr10` with
//! AltiVec, VSX, MMA, HTM, crypto; and `-mcpu=e500 +spe` for SPE), sampling
//! every key with zeroed, structured and random operand fields and
//! classifying by mnemonic. POWER10 prefixed instructions (primary opcode 1)
//! are 8 bytes long and skipped.
//!
//! The Signal Processing Engine (e500, `powerpcspe`) reuses primary opcode 4:
//! most SPE encodings are also valid AltiVec encodings. VMX (and the crypto
//! instructions, which live in the same space) are therefore reported only
//! together with a vector load or store (`lvx`/`stvx` family or VSX
//! loads/stores), which SPE code never contains; SPE is reported from the
//! opcode-4 encodings that exist only in SPE.

use super::{bit_of, ExtDef, Tally};
use crate::types::{Endianness, ExtensionCategory::*, Isa};

const VEC_MEM_IDX: usize = 0;

pub(super) const EXTS: &[ExtDef] = &[
    ExtDef::hidden("vec-mem"),
    ExtDef::new("VMX", Simd).anchored(VEC_MEM_IDX),
    ExtDef::new("VSX", Simd),
    ExtDef::narrow("MMA", MachineLearning),
    ExtDef::narrow("HTM", Transactional),
    ExtDef::new("Crypto", Crypto).anchored(VEC_MEM_IDX),
    ExtDef::new("SPE", Simd),
];

const fn b(name: &str) -> u64 {
    bit_of(EXTS, name)
}
