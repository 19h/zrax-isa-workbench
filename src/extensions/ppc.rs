pub(super) fn scan(code: &[u8], _isa: Isa, e: Endianness, t: &mut Tally) {
    let be = e == Endianness::Big;
    let mut i = 0usize;
    while i + 4 <= code.len() {
        let a = [code[i], code[i + 1], code[i + 2], code[i + 3]];
        let w = if be { u32::from_be_bytes(a) } else { u32::from_le_bytes(a) };
        if w >> 26 == 1 {
            // Prefixed instruction: prefix word + suffix word.
            t.insn(0);
            i += 8;
            continue;
        }
        match classify(w) {
            Some(m) => t.insn(m),
            None => t.invalid(),
        }
        i += 4;
    }
}

/// Evidence bits of one (non-prefix) instruction word; `None` if invalid.
pub(crate) fn classify(w: u32) -> Option<u64> {
    let p = (w >> 26) as u8;
    let Some(row) = KEYED.iter().position(|&k| k == p) else {
        return (PRIMARY_VALID >> p & 1 != 0).then_some(0);
    };
    let key = (w & 0x7FF) as usize;
    let class = CLASSES[row][key / 2] >> (4 * (key & 1)) & 0xF;
    Some(match class {
        0 => return None,
        2 => VMX,
        3 => VSX,
        4 => MMA,
        5 => VMX | VEC_MEM,
        6 => VSX | VEC_MEM,
        7 => HTM,
        8 => VMX | CRYPTO,
        9 => SPE,
        _ => 0,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::extensions::test_util::{be_words, detect, le_words};

    /// Encodings from `llvm-mc -triple=powerpc64 -mcpu=pwr10 -show-encoding`
    /// and `-triple=powerpc -mcpu=e500 -mattr=+spe`.
    #[rustfmt::skip]
    const WORDS: &[(u32, Option<u64>)] = &[
        (0x10011080, Some(VMX)),           // vadduwm 0, 1, 2
        (0x1001102A, Some(VMX)),           // vsel 0, 1, 2, 0
        (0x1001112B, Some(VMX)),           // vperm 0, 1, 2, 4
        (0x7C0018CE, Some(VMX | VEC_MEM)), // lvx 0, 0, 3
        (0x7C0019CE, Some(VMX | VEC_MEM)), // stvx 0, 0, 3
        (0x7C001E99, Some(VSX | VEC_MEM)), // lxvd2x 32, 0, 3
        (0x7C001F99, Some(VSX | VEC_MEM)), // stxvd2x 32, 0, 3
        (0xF4030019, Some(VSX | VEC_MEM)), // lxv 32, 16(3)
        (0xF0011100, Some(VSX)),           // xsadddp 0, 1, 2
        (0xF0011300, Some(VSX)),           // xvadddp 0, 1, 2
        (0xF0011490, Some(VSX)),           // xxlor 0, 1, 2
        (0x7C230066, Some(VSX)),           // mfvsrd 3, 1
        (0xEC011018, Some(MMA)),           // xvi8ger4 0, 1, 2
        (0x7C00051D, Some(HTM)),           // tbegin. 0
        (0x10011508, Some(VMX | CRYPTO)),  // vcipher 0, 1, 2
        (0x100114C8, Some(VMX | CRYPTO)),  // vpmsumd 0, 1, 2
        (0x10640301, Some(SPE)),           // evldd 3, 0(4)
        (0x10640321, Some(VMX)),           // evstdd 3, 0(4) = AltiVec vmhraddshs 3, 4, 0, 12
        (0x7C632214, Some(0)),             // add 3, 3, 4
        (0x38630001, Some(0)),             // addi 3, 3, 1
        (0x4E800020, Some(0)),             // blr
        (0xE8610010, Some(0)),             // ld 3, 16(1)
        (0xFC21102A, Some(0)),             // fadd 1, 1, 2
        (0x7C0004AC, Some(0)),             // hwsync
        (0x7C2004AC, Some(0)),             // lwsync
        (0x00000000, None),
    ];

    #[test]
    fn ppc_encodings() {
        for &(w, want) in WORDS {
            assert_eq!(classify(w), want, "{w:#010X}");
        }
    }

    #[test]
    fn altivec_needs_vector_memory_ops() {
        // Opcode-4 arithmetic alone (as SPE code looks to an AltiVec decoder): no VMX.
        let f = [0x10011080u32, 0x1001102A, 0x38630001, 0x7C632214];
        let code = be_words(&f.repeat(400));
        assert!(detect(&code, Isa::Ppc, Endianness::Big).is_empty());
        let f = [0x7C0018CEu32, 0x10011080, 0x1001102A, 0x7C0019CE, 0x38630010, 0x4200FFEC];
        let code = be_words(&f.repeat(400));
        assert_eq!(detect(&code, Isa::Ppc, Endianness::Big), vec!["VMX"]);
        let code = le_words(&f.repeat(400));
        assert_eq!(detect(&code, Isa::Ppc64, Endianness::Little), vec!["VMX"]);
    }
}
